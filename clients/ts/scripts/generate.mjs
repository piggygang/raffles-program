// Generates the client from the IDL of record, idls/raffles.json:
//
//   src/generated/   Codama's client: instructions, accounts, events, types,
//                    errors and constants
//   src/release.ts   the release the IDL belongs to
//   idl/raffles.json the IDL itself, which the package exports as ./idl.json
//
// Nothing it writes is committed. Run it through `npm run build`.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { rootNodeFromAnchor } from "@codama/nodes-from-anchor";
import { renderVisitor } from "@codama/renderers-js";
import { createFromRoot } from "codama";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const idlPath = join(packageDir, "..", "..", "idls", "raffles.json");

const idl = JSON.parse(readFileSync(idlPath, "utf8"));
const { version } = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));
if (idl.metadata.version !== version) {
  throw new Error(
    `package.json is at ${version}, but idls/raffles.json is the IDL of ${idl.metadata.version}: ` +
      "a release has one version (docs/releases.md)",
  );
}

const codama = createFromRoot(rootNodeFromAnchor(idl));
await codama.accept(
  renderVisitor(packageDir, {
    deleteFolderBeforeRendering: true,
    // Node resolves `./x.js`, not `./x`: the package is plain ES modules.
    importExtension: "js",
    // package.json is written by hand.
    syncPackageJson: false,
  }),
);

writeFileSync(
  join(packageDir, "src", "release.ts"),
  [
    "// Generated by scripts/generate.mjs from idls/raffles.json.",
    "",
    "/** The release this client belongs to: its tag without the `v`. */",
    `export const VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n"),
);

mkdirSync(join(packageDir, "idl"), { recursive: true });
copyFileSync(idlPath, join(packageDir, "idl", "raffles.json"));

console.log(`Generated the client of raffles ${version} (${idl.address}).`);
